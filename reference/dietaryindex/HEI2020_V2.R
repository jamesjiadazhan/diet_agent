# Frozen dietaryindex 2.1, commit 0cb60bd67c2942d954d20637500c4a921a935f51
HEI2020_V2 <- 
function (SERV_DATA, RESPONDENTID, AGE, TOTALKCAL_HEI2020, TOTALFRT_SERV_HEI2020, FRT_SERV_HEI2020, VEG_SERV_HEI2020, GREENNBEAN_SERV_HEI2020, 
    TOTALPRO_SERV_HEI2020, SEAPLANTPRO_SERV_HEI2020, WHOLEGRAIN_SERV_HEI2020, DAIRY_SERV_HEI2020, FATTYACID_SERV_HEI2020, 
    REFINEDGRAIN_SERV_HEI2020, SODIUM_SERV_HEI2020, ADDEDSUGAR_SERV_HEI2020, SATFAT_SERV_HEI2020) 
{
    HEI2020_MIN = 0
    HEI2020_MAX1 = 5
    HEI2020_MAX2 = 10
    HEI2020_MIN_TOTALFRT_SERV = 0
    HEI2020_MAX_TOTALFRT_SERV = 0.8
    HEI2020_MIN_FRT_SERV = 0
    HEI2020_MAX_FRT_SERV = 0.4
    HEI2020_MIN_VEG_SERV = 0
    HEI2020_MAX_VEG_SERV = 1.1
    HEI2020_MIN_GREENNBEAN_SERV = 0
    HEI2020_MAX_GREENNBEAN_SERV = 0.2
    HEI2020_MIN_TOTALPRO_SERV = 0
    HEI2020_MAX_TOTALPRO_SERV = 2.5
    HEI2020_MIN_SEAPLANTPRO_SERV = 0
    HEI2020_MAX_SEAPLANTPRO_SERV = 0.8
    HEI2020_MIN_WHOLEGRAIN_SERV = 0
    HEI2020_MAX_WHOLEGRAIN_SERV = 1.5
    HEI2020_MIN_DAIRY_SERV = 0
    HEI2020_MAX_DAIRY_SERV = 1.3
    HEI2020_MIN_FATTYACID_SERV = 1.2
    HEI2020_MAX_FATTYACID_SERV = 2.5
    HEI2020_MIN_REFINEDGRAIN_SERV = 4.3
    HEI2020_MAX_REFINEDGRAIN_SERV = 1.8
    HEI2020_MIN_SODIUM_SERV = 2
    HEI2020_MAX_SODIUM_SERV = 1.1
    HEI2020_MIN_ADDEDSUGAR_SERV = 26
    HEI2020_MAX_ADDEDSUGAR_SERV = 6.5
    HEI2020_MIN_SATFAT_SERV = 16
    HEI2020_MAX_SATFAT_SERV = 8
    HEI2020_TODDLERS_MIN_TOTALFRT_SERV = 0
    HEI2020_TODDLERS_MAX_TOTALFRT_SERV = 0.7
    HEI2020_TODDLERS_MIN_FRT_SERV = 0
    HEI2020_TODDLERS_MAX_FRT_SERV = 0.3
    HEI2020_TODDLERS_MIN_VEG_SERV = 0
    HEI2020_TODDLERS_MAX_VEG_SERV = 0.9
    HEI2020_TODDLERS_MIN_GREENNBEAN_SERV = 0
    HEI2020_TODDLERS_MAX_GREENNBEAN_SERV = 0.1
    HEI2020_TODDLERS_MIN_TOTALPRO_SERV = 0
    HEI2020_TODDLERS_MAX_TOTALPRO_SERV = 2
    HEI2020_TODDLERS_MIN_SEAPLANTPRO_SERV = 0
    HEI2020_TODDLERS_MAX_SEAPLANTPRO_SERV = 0.5
    HEI2020_TODDLERS_MIN_WHOLEGRAIN_SERV = 0
    HEI2020_TODDLERS_MAX_WHOLEGRAIN_SERV = 1.5
    HEI2020_TODDLERS_MIN_DAIRY_SERV = 0
    HEI2020_TODDLERS_MAX_DAIRY_SERV = 2
    HEI2020_TODDLERS_MIN_FATTYACID_SERV = 0.9
    HEI2020_TODDLERS_MAX_FATTYACID_SERV = 1.5
    HEI2020_TODDLERS_MIN_REFINEDGRAIN_SERV = 3.4
    HEI2020_TODDLERS_MAX_REFINEDGRAIN_SERV = 1.5
    HEI2020_TODDLERS_MIN_SODIUM_SERV = 1.7
    HEI2020_TODDLERS_MAX_SODIUM_SERV = 1.1
    HEI2020_TODDLERS_MIN_ADDEDSUGAR_SERV = 13.8
    HEI2020_TODDLERS_MAX_ADDEDSUGAR_SERV = 0
    HEI2020_TODDLERS_MIN_SATFAT_SERV = 18.2
    HEI2020_TODDLERS_MAX_SATFAT_SERV = 12.2
    HEI2020_HEALTHY1 = function(actual, min, max) {
        case_when(actual >= max ~ HEI2020_MAX1, actual <= min ~ HEI2020_MIN, TRUE ~ HEI2020_MIN + (actual - min) * HEI2020_MAX1/(max - 
            min))
    }
    HEI2020_HEALTHY2 = function(actual, min, max) {
        case_when(actual >= max ~ HEI2020_MAX2, actual <= min ~ HEI2020_MIN, TRUE ~ HEI2020_MIN + (actual - min) * HEI2020_MAX2/(max - 
            min))
    }
    HEI2020_UNHEALTHY = function(actual, min, max) {
        case_when(actual >= min ~ HEI2020_MIN, actual <= max ~ HEI2020_MAX2, TRUE ~ HEI2020_MIN + (actual - min) * HEI2020_MAX2/(max - 
            min))
    }
    SERV_DATA = SERV_DATA %>% dplyr::mutate(RESPONDENTID = RESPONDENTID, AGE = AGE, TOTALKCAL_HEI2020 = TOTALKCAL_HEI2020, 
        TOTALFRT_SERV_HEI2020 = TOTALFRT_SERV_HEI2020/(TOTALKCAL_HEI2020/1000), FRT_SERV_HEI2020 = (FRT_SERV_HEI2020)/(TOTALKCAL_HEI2020/1000), 
        VEG_SERV_HEI2020 = (VEG_SERV_HEI2020)/(TOTALKCAL_HEI2020/1000), GREENNBEAN_SERV_HEI2020 = (GREENNBEAN_SERV_HEI2020)/(TOTALKCAL_HEI2020/1000), 
        TOTALPRO_SERV_HEI2020 = (TOTALPRO_SERV_HEI2020)/(TOTALKCAL_HEI2020/1000), SEAPLANTPRO_SERV_HEI2020 = (SEAPLANTPRO_SERV_HEI2020)/(TOTALKCAL_HEI2020/1000), 
        WHOLEGRAIN_SERV_HEI2020 = WHOLEGRAIN_SERV_HEI2020/(TOTALKCAL_HEI2020/1000), DAIRY_SERV_HEI2020 = DAIRY_SERV_HEI2020/(TOTALKCAL_HEI2020/1000), 
        FATTYACID_SERV_HEI2020 = FATTYACID_SERV_HEI2020, REFINEDGRAIN_SERV_HEI2020 = REFINEDGRAIN_SERV_HEI2020/(TOTALKCAL_HEI2020/1000), 
        SODIUM_SERV_HEI2020 = (SODIUM_SERV_HEI2020/1000)/(TOTALKCAL_HEI2020/1000), ADDEDSUGAR_SERV_HEI2020 = ((ADDEDSUGAR_SERV_HEI2020 * 
            4 * 4)/TOTALKCAL_HEI2020) * 100, SATFAT_SERV_HEI2020 = ((SATFAT_SERV_HEI2020 * 9)/TOTALKCAL_HEI2020) * 100) %>% 
        mutate(HEI2020_TOTALFRT = case_when(AGE >= 2 ~ HEI2020_HEALTHY1(TOTALFRT_SERV_HEI2020, HEI2020_MIN_TOTALFRT_SERV, 
            HEI2020_MAX_TOTALFRT_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_HEALTHY1(TOTALFRT_SERV_HEI2020, HEI2020_TODDLERS_MIN_TOTALFRT_SERV, 
            HEI2020_TODDLERS_MAX_TOTALFRT_SERV), ), HEI2020_FRT = case_when(AGE >= 2 ~ HEI2020_HEALTHY1(FRT_SERV_HEI2020, 
            HEI2020_MIN_FRT_SERV, HEI2020_MAX_FRT_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_HEALTHY1(FRT_SERV_HEI2020, HEI2020_TODDLERS_MIN_FRT_SERV, 
            HEI2020_TODDLERS_MAX_FRT_SERV), ), HEI2020_VEG = case_when(AGE >= 2 ~ HEI2020_HEALTHY1(VEG_SERV_HEI2020, HEI2020_MIN_VEG_SERV, 
            HEI2020_MAX_VEG_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_HEALTHY1(VEG_SERV_HEI2020, HEI2020_TODDLERS_MIN_VEG_SERV, 
            HEI2020_TODDLERS_MAX_VEG_SERV), ), HEI2020_GREENNBEAN = case_when(AGE >= 2 ~ HEI2020_HEALTHY1(GREENNBEAN_SERV_HEI2020, 
            HEI2020_MIN_GREENNBEAN_SERV, HEI2020_MAX_GREENNBEAN_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_HEALTHY1(GREENNBEAN_SERV_HEI2020, 
            HEI2020_TODDLERS_MIN_GREENNBEAN_SERV, HEI2020_TODDLERS_MAX_GREENNBEAN_SERV), ), HEI2020_TOTALPRO = case_when(AGE >= 
            2 ~ HEI2020_HEALTHY1(TOTALPRO_SERV_HEI2020, HEI2020_MIN_TOTALPRO_SERV, HEI2020_MAX_TOTALPRO_SERV), AGE < 2 & 
            AGE >= 1 ~ HEI2020_HEALTHY1(TOTALPRO_SERV_HEI2020, HEI2020_TODDLERS_MIN_TOTALPRO_SERV, HEI2020_TODDLERS_MAX_TOTALPRO_SERV), 
            ), HEI2020_SEAPLANTPRO = case_when(AGE >= 2 ~ HEI2020_HEALTHY1(SEAPLANTPRO_SERV_HEI2020, HEI2020_MIN_SEAPLANTPRO_SERV, 
            HEI2020_MAX_SEAPLANTPRO_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_HEALTHY1(SEAPLANTPRO_SERV_HEI2020, HEI2020_TODDLERS_MIN_SEAPLANTPRO_SERV, 
            HEI2020_TODDLERS_MAX_SEAPLANTPRO_SERV), ), HEI2020_WHOLEGRAIN = case_when(AGE >= 2 ~ HEI2020_HEALTHY2(WHOLEGRAIN_SERV_HEI2020, 
            HEI2020_MIN_WHOLEGRAIN_SERV, HEI2020_MAX_WHOLEGRAIN_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_HEALTHY2(WHOLEGRAIN_SERV_HEI2020, 
            HEI2020_TODDLERS_MIN_WHOLEGRAIN_SERV, HEI2020_TODDLERS_MAX_WHOLEGRAIN_SERV), ), HEI2020_DAIRY = case_when(AGE >= 
            2 ~ HEI2020_HEALTHY2(DAIRY_SERV_HEI2020, HEI2020_MIN_DAIRY_SERV, HEI2020_MAX_DAIRY_SERV), AGE < 2 & AGE >= 1 ~ 
            HEI2020_HEALTHY2(DAIRY_SERV_HEI2020, HEI2020_TODDLERS_MIN_DAIRY_SERV, HEI2020_TODDLERS_MAX_DAIRY_SERV), ), HEI2020_FATTYACID = case_when(AGE >= 
            2 ~ HEI2020_HEALTHY2(FATTYACID_SERV_HEI2020, HEI2020_MIN_FATTYACID_SERV, HEI2020_MAX_FATTYACID_SERV), AGE < 2 & 
            AGE >= 1 ~ HEI2020_HEALTHY2(FATTYACID_SERV_HEI2020, HEI2020_TODDLERS_MIN_FATTYACID_SERV, HEI2020_TODDLERS_MAX_FATTYACID_SERV), 
            ), HEI2020_REFINEDGRAIN = case_when(AGE >= 2 ~ HEI2020_UNHEALTHY(REFINEDGRAIN_SERV_HEI2020, HEI2020_MIN_REFINEDGRAIN_SERV, 
            HEI2020_MAX_REFINEDGRAIN_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_UNHEALTHY(REFINEDGRAIN_SERV_HEI2020, HEI2020_TODDLERS_MIN_REFINEDGRAIN_SERV, 
            HEI2020_TODDLERS_MAX_REFINEDGRAIN_SERV), ), HEI2020_SODIUM = case_when(AGE >= 2 ~ HEI2020_UNHEALTHY(SODIUM_SERV_HEI2020, 
            HEI2020_MIN_SODIUM_SERV, HEI2020_MAX_SODIUM_SERV), AGE < 2 & AGE >= 1 ~ HEI2020_UNHEALTHY(SODIUM_SERV_HEI2020, 
            HEI2020_TODDLERS_MIN_SODIUM_SERV, HEI2020_TODDLERS_MAX_SODIUM_SERV), ), HEI2020_ADDEDSUGAR = case_when(AGE >= 
            2 ~ HEI2020_UNHEALTHY(ADDEDSUGAR_SERV_HEI2020, HEI2020_MIN_ADDEDSUGAR_SERV, HEI2020_MAX_ADDEDSUGAR_SERV), AGE < 
            2 & AGE >= 1 ~ HEI2020_UNHEALTHY(ADDEDSUGAR_SERV_HEI2020, HEI2020_TODDLERS_MIN_ADDEDSUGAR_SERV, HEI2020_TODDLERS_MAX_ADDEDSUGAR_SERV), 
            ), HEI2020_SATFAT = case_when(AGE >= 2 ~ HEI2020_UNHEALTHY(SATFAT_SERV_HEI2020, HEI2020_MIN_SATFAT_SERV, HEI2020_MAX_SATFAT_SERV), 
            AGE < 2 & AGE >= 1 ~ HEI2020_UNHEALTHY(SATFAT_SERV_HEI2020, HEI2020_TODDLERS_MIN_SATFAT_SERV, HEI2020_TODDLERS_MAX_SATFAT_SERV), 
            ), HEI2020_ALL = HEI2020_TOTALFRT + HEI2020_FRT + HEI2020_VEG + HEI2020_GREENNBEAN + HEI2020_TOTALPRO + HEI2020_SEAPLANTPRO + 
            HEI2020_WHOLEGRAIN + HEI2020_DAIRY + HEI2020_FATTYACID + HEI2020_REFINEDGRAIN + HEI2020_SODIUM + HEI2020_ADDEDSUGAR + 
            HEI2020_SATFAT)
    for (i in 1:length(SERV_DATA$TOTALKCAL_HEI2020)) {
        if (SERV_DATA$TOTALKCAL_HEI2020[i] == 0) {
            SERV_DATA$HEI2020_TOTALFRT[i] = 0
            SERV_DATA$HEI2020_FRT[i] = 0
            SERV_DATA$HEI2020_VEG[i] = 0
            SERV_DATA$HEI2020_GREENNBEAN[i] = 0
            SERV_DATA$HEI2020_TOTALPRO[i] = 0
            SERV_DATA$HEI2020_SEAPLANTPRO[i] = 0
            SERV_DATA$HEI2020_WHOLEGRAIN[i] = 0
            SERV_DATA$HEI2020_DAIRY[i] = 0
            SERV_DATA$HEI2020_FATTYACID[i] = 0
            SERV_DATA$HEI2020_REFINEDGRAIN[i] = 0
            SERV_DATA$HEI2020_ADDEDSUGAR[i] = 0
            SERV_DATA$HEI2020_ALL[i] = 0
        }
    }
    SERV_DATA %>% dplyr::select(RESPONDENTID, AGE, TOTALKCAL_HEI2020, HEI2020_ALL, HEI2020_TOTALFRT, HEI2020_FRT, HEI2020_VEG, 
        HEI2020_GREENNBEAN, HEI2020_TOTALPRO, HEI2020_SEAPLANTPRO, HEI2020_WHOLEGRAIN, HEI2020_DAIRY, HEI2020_FATTYACID, 
        HEI2020_REFINEDGRAIN, HEI2020_SODIUM, HEI2020_ADDEDSUGAR, HEI2020_SATFAT)
}
